#!/usr/bin/env node
// K3.4 (R1 §7): writes packages/vdb/src/tools/frame/mie-table.ts, the Lorenz-Mie phase tables of the
// 'lorenz-mie' and 'lorenz-mie-rgb' phase functions, from our port of mjurczyk's generator
// (`vdbFrameMieTable`, tools/frame/mie.ts; his scripts/mie-phase-table.mjs at 75e7345, MIT). The tables are a
// build output with the generator as the source, not data copied from his repo.
//
//   pnpm build && node scripts/k3/mie-phase-table.mjs [--check]
//
// --check: regenerate and compare with the committed module (exit 1 on a difference); writes nothing.
// Takes ~5-10 s (four tables of 2048 angles × 1201 droplet radii).

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { vdbFrameMieChannel, vdbFrameMieFormat, vdbFrameMieRgbChannels, vdbFrameMieTable } from "../../packages/vdb/dist/tools/frame/mie.js";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const outputPath = path.join(repoRoot, "packages/vdb/src/tools/frame/mie-table.ts");
const check = process.argv.includes("--check");

const started = Date.now();
const mie = vdbFrameMieTable(vdbFrameMieChannel.wavelength, vdbFrameMieChannel.refractiveIndex);
const rgb = vdbFrameMieRgbChannels.map((c) => vdbFrameMieTable(c.wavelength, c.refractiveIndex));
const size = mie.table.length;
const rgbValues = Array.from({ length: size }, (_, j) => rgb.map(({ table }) => vdbFrameMieFormat(table[j])).join(",")).join(",");
const describe = (key, format) => rgb.map((r) => format(r[key])).join(" / ");

const text = `// Generated by scripts/k3/mie-phase-table.mjs from vdbFrameMieTable (./mie.ts). Do not edit.
// The generator is a port of mjurczyk/openvdb (MIT) scripts/mie-phase-table.mjs, commit 75e7345
// (Copyright (c) mjurczyk/openvdb contributors; see THIRD_PARTY.md); the numbers are its output.
// Lorenz-Mie phase functions of cumulus water droplets (Deirmendjian C1), divided by the isotropic phase
// 1 / (4 PI). Texel u (0 to 1) is at the scattering angle PI * u^2.
// 'lorenz-mie': ${vdbFrameMieChannel.wavelength * 1000} nm, n ${vdbFrameMieChannel.refractiveIndex}, asymmetry g = ${mie.asymmetry.toFixed(4)}, forward peak ${vdbFrameMieFormat(mie.peak)}.
// 'lorenz-mie-rgb': ${vdbFrameMieRgbChannels.map((c) => c.wavelength * 1000).join(" / ")} nm (red, green, blue),
// n ${vdbFrameMieRgbChannels.map((c) => c.refractiveIndex).join(" / ")}, asymmetry g = ${describe("asymmetry", (v) => v.toFixed(4))},
// forward peak ${describe("peak", vdbFrameMieFormat)}.

/** Texels of each table. */
export const frameMieTableSize = ${size};

/** 'lorenz-mie' (550 nm). */
export const frameMieTable = new Float32Array([${Array.from(mie.table, vdbFrameMieFormat).join(",")}]);

/** 'lorenz-mie-rgb': red, green and blue values of each texel. */
export const frameMieRgbTable = new Float32Array([${rgbValues}]);
`;

const seconds = ((Date.now() - started) / 1000).toFixed(1);
if (check) {
  const committed = readFileSync(outputPath, "utf8");
  if (committed !== text) {
    console.error(`mie-table.ts differs from the generator output (${seconds} s)`);
    process.exit(1);
  }
  console.log(`mie-table.ts matches the generator (${seconds} s)`);
} else {
  writeFileSync(outputPath, text);
  console.log(`wrote ${path.relative(repoRoot, outputPath)} (${seconds} s): g ${mie.asymmetry.toFixed(4)}, rgb g ${describe("asymmetry", (v) => v.toFixed(4))}`);
}
